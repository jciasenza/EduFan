-- Ejecutar una sola vez para crear/configurar public.game_content.

create table if not exists public.game_content (
  id bigint generated by default as identity primary key,
  game_id text not null,
  language text not null check (language in ('es', 'en')),
  volume integer not null check (volume > 0),
  level integer not null default 1 check (level > 0),
  content jsonb not null check (
    case
      when jsonb_typeof(content) = 'array' then jsonb_array_length(content) > 0
      else false
    end
  ),
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (game_id, language, volume, level)
);

alter table public.game_content
  add column if not exists level integer not null default 1;

alter table public.game_content
  drop constraint if exists game_content_game_id_language_volume_key;
alter table public.game_content
  drop constraint if exists game_content_game_id_language_volume_level_key;
alter table public.game_content
  add constraint game_content_game_id_language_volume_level_key
  unique (game_id, language, volume, level);

alter table public.game_content enable row level security;

drop policy if exists "Anyone can read published game content"
  on public.game_content;
create policy "Anyone can read published game content"
  on public.game_content for select
  to anon, authenticated
  using (is_published = true);

revoke all on public.game_content from anon, authenticated;
grant select on public.game_content to anon, authenticated;
